def edge_point(i, axis, v):
    """FOOT の辺 i の上で axis（0=x, 1=y）が v の点。"""
    a, b = FOOT[i], FOOT[(i + 1) % len(FOOT)]
    t = (v - a[axis]) / (b[axis] - a[axis])
    return (a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t)


def edge_span(i, axis, v0, v1):
    """辺 i の axis 座標 v0 -> v1 の部分線 (a, b)。"""
    return edge_point(i, axis, v0), edge_point(i, axis, v1)


def west_x(y):
    """アリーナ西壁の室内側の面の X（辺 12 は 0.5 m 斜めに振れている）。"""
    return edge_point(E_WEST, 1, y)[0] + 0.30


def south_y(x):
    """南壁（辺 13）の室内側の面の Y。"""
    return edge_point(E_SOUTH, 0, x)[1] + 0.30
