import math


def edge_pt(i, x, off):
    """外周の辺 i（OUTLINE[i] -> OUTLINE[i + 1]）の上で X が x の点を、外面から off だけ室内へ寄せる。"""
    a, b = OUTLINE[i], OUTLINE[(i + 1) % len(OUTLINE)]
    t = (x - a[0]) / (b[0] - a[0])
    dx, dy = b[0] - a[0], b[1] - a[1]
    L = math.hypot(dx, dy)
    return (x - dy / L * off, a[1] + dy * t + dx / L * off)


def edge_ang(i):
    """辺 i の窓を向く T の角度（正面 = 外向きの法線）。"""
    a, b = OUTLINE[i], OUTLINE[(i + 1) % len(OUTLINE)]
    dx, dy = b[0] - a[0], b[1] - a[1]
    return math.atan2(-dy, -dx)

